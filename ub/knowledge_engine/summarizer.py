def _parse_requirements(path: Path) -> List[str]:
    if not path.exists():
        return []
    out = []
    for line in path.read_text(errors="ignore").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            out.append(line)
    return out


def dependency_summary() -> Dict:
    backend = _parse_requirements(TGIE_ROOT / "backend" / "requirements.txt")
    bling = _parse_requirements(TGIE_ROOT / "blue_team" / "bling" / "requirements.txt")
    pkg = TGIE_ROOT / "frontend" / "package.json"
    frontend_deps: Dict[str, str] = {}
    if pkg.exists():
        try:
            j = json.loads(pkg.read_text())
            frontend_deps = {**j.get("dependencies", {}), **j.get("devDependencies", {})}
        except Exception:
            pass
    return {
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "backend_python": backend,
        "bling_python": bling,
        "frontend_npm": frontend_deps,
        "ub_runtime": {
            "llm": "Ollama (local) — llama3.1:8b primary, llama3.2:3b fast fallback",
            "embeddings": "nomic-embed-text (local)",
            "python": "stdlib + numpy (no heavy ML deps; no fine-tuning)",
        },
        "notes": [
            "scipy==1.13.0 has no wheel for Python 3.14 → local backend needs Python 3.11 or relaxed pins",
            "xgboost requires libomp.dylib; gracefully falls back to rule-based if absent",
        ],
    }



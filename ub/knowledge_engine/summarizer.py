DATA_DIR = Path(__file__).resolve().parents[1] / "data"


def _counts() -> Dict[str, Dict[str, int]]:
    by_comp: Dict[str, Dict[str, int]] = {}
    for fp in iter_files():
        rel = str(fp.relative_to(TGIE_ROOT))
        comp = classify_component(rel)
        d = by_comp.setdefault(comp, {"files": 0, "lines": 0})
        d["files"] += 1
        try:
            d["lines"] += sum(1 for _ in fp.open("r", encoding="utf-8", errors="ignore"))
        except OSError:
            pass
    return by_comp



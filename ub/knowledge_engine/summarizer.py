def generate_all(data_dir: Path = DATA_DIR) -> List[str]:
    data_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, fn in GENERATORS.items():
        (data_dir / name).write_text(json.dumps(fn(), indent=2))
        written.append(name)
    return written


